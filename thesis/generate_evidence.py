#!/usr/bin/env python3
"""Typeset the retained evidence; do not rerun or modify detector experiments."""

import csv
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "thesis/generated"
SOURCES = {}
NAMES = {"UNSW-Chromecast": "Chromecast", "UNSW-Samsung-Camera": "Samsung camera",
         "D-LinkDayCam5": "D-Link Camera 5"}


def read(path):
    raw = (ROOT / path).read_bytes()
    SOURCES[path] = hashlib.sha256(raw).hexdigest()
    return json.loads(raw)


def rows(name, data):
    (OUT / (name + ".tex")).write_text(
        "% Generated by thesis/generate_evidence.py; see evidence_manifest.json.\n"
        + "\n".join(" & ".join(map(str, row)) + r" \\" for row in data) + "\n"
    )


def csv_rows(name, header, data):
    with (OUT / (name + ".csv")).open("w", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(header)
        writer.writerows(data)


def pct(value):
    return "--" if value is None else f"{100 * value:.2f}\\%"


def metrics(row):
    tp, fp, fn, tn = (row[k] for k in
                      ("true_positive", "false_positive", "false_negative", "true_negative"))
    assert min(tp, fp, fn, tn) >= 0
    assert sum((tp, fp, fn, tn)) == row.get("window_count", row.get("matched_window_count"))
    for key, numerator, denominator in [("precision", tp, tp + fp), ("recall", tp, tp + fn),
                                        ("false_positive_rate", fp, fp + tn),
                                        ("f1_score", 2 * tp, 2 * tp + fp + fn)]:
        if key in row and row[key] is not None and denominator:
            assert math.isclose(row[key], numerator / denominator, abs_tol=1e-12), key
    return [tp, fp, fn, tn, pct(tp / (tp + fp) if tp + fp else None),
            pct(tp / (tp + fn) if tp + fn else None), pct(row["f1_score"])]


def main():
    OUT.mkdir(exist_ok=True)
    partition_rows, profiles, parameters, model_plot, development = [], [], [], [], []
    chronology, count_cutoffs, quantile_ranks = {}, [], []
    roles = {"fit": "Fit", "calibration": "Calibration", "development_test": "Development",
             "final_test": "Final partition"}
    for dataset, filename in [("D-LinkDayCam5", "d_link_day_cam5"),
                              ("UNSW-Chromecast", "unsw_chromecast"),
                              ("UNSW-Samsung-Camera", "unsw_samsung_camera")]:
        config = read(f"configs/{filename}.json")
        model = read(f"artifacts/{dataset}/model.json")
        threshold = read(f"artifacts/{dataset}/threshold.json")
        calibration_n = threshold["calibration_window_count"]
        quantile_ranks.append([NAMES[dataset] + ", reference", calibration_n,
                               f"{1 + (calibration_n - 1) * threshold['quantile']:.2f}"])
        fit_bounds = []
        for role, captures in config["ingest"]["partitions"].items():
            count, positive, silent = 0, 0, 0
            for capture in captures:
                windows = read(f"data/processed/{dataset}/{capture}.json")["windows"]
                observed = [w for w in windows if w["counts"] is not None]
                count += len(observed)
                silent += sum(sum(w["counts"]) == 0 for w in observed)
                if role == "fit":
                    fit_bounds.extend((w["start_utc"], w["end_utc"]) for w in observed)
                if dataset != "D-LinkDayCam5":
                    labels = read(f"data/labels/{dataset}/{capture}.json")
                    labels = labels["windows"]
                    positive += sum(x["is_attack"] for x in labels)
            dates = [c[-10:] for c in captures]
            dates = dates[0] if len(dates) == 1 else dates[0] + " to " + dates[-1]
            partition_rows.append([NAMES[dataset], roles[role], dates, count,
                                   "--" if dataset == "D-LinkDayCam5" else positive, silent])
        chronology[dataset] = {"fit_rows": len(fit_bounds),
                               "distinct_fit_bounds": len(set(fit_bounds)),
                               "repeated_fit_bounds": len(fit_bounds) - len(set(fit_bounds))}
        profiles.append([NAMES[dataset], *[f"{100*p:.3f}" for p in model["mean_probabilities"]],
                         f"{model['concentration']:.3f}", f"{model['psi']:.5f}"])
        parameters.append([NAMES[dataset], *[f"{a:.6g}" for a in model["alpha"]],
                           model["fit_diagnostics"]["iterations"],
                           f"{threshold['threshold']:.4f}", f"{threshold['score_iqr']:.4f}"])
        total, arp = (threshold["count_tails"][k]["threshold"] for k in ["total", "arp"])
        count_cutoffs.append([NAMES[dataset], f"{total:.4f}", f"{math.expm1(total):.0f}",
                              f"{arp:.4f}", f"{math.expm1(arp):.0f}"])
        for k, p in enumerate(model["mean_probabilities"]):
            model_plot.append([dataset, k + 1, 100*p])
        if dataset != "D-LinkDayCam5":
            result = read(f"reports/{dataset}/evaluation_statistics.json")
            development.append([NAMES[dataset], *metrics(result)])
    rows("partitions", partition_rows)
    rows("profiles", profiles)
    rows("parameters", parameters)
    rows("count_cutoffs", count_cutoffs)
    rows("development", development)
    for dataset in NAMES:
        csv_rows("profile_" + dataset, ["category", "percent"],
                 [[k, p] for d, k, p in model_plot if d == dataset])

    final = read("reports/final_evaluation/results.json")
    assert final["frozen_inputs_unchanged"]
    final_rows, interval_rows, final_decisions, cases = [], [], {}, []
    case_specs = {
        ("UNSW-Chromecast", "2018-10-25T07:20:00Z"): ("A", "TP"),
        ("UNSW-Chromecast", "2018-10-25T07:50:00Z"): ("B", "FN"),
        ("UNSW-Chromecast", "2018-10-24T16:30:00Z"): ("C", "FP"),
        ("UNSW-Samsung-Camera", "2018-06-05T18:50:00Z"): ("D", "TP"),
        ("UNSW-Samsung-Camera", "2018-06-05T19:00:00Z"): ("E", "FN"),
    }
    for row in final["results"]:
        metrics(row)
        assert row["threshold_updates"] == row["model_refits"] == 0
        labels = {}
        for capture in row["capture_ids"]:
            for label in read(f"data/labels/{row['dataset']}/{capture}.json")["windows"]:
                key = capture, label["window_start_utc"], label["window_end_utc"]
                assert key not in labels
                labels[key] = label["is_attack"]
        decisions, confusion = {}, dict.fromkeys(["TP", "FP", "FN", "TN"], 0)
        for event in read(f"artifacts/final_evaluation/{row['dataset']}/{row['mode']}_events.json"):
            key = event["capture_id"], event["window_start_utc"], event["window_end_utc"]
            assert key in labels and key not in decisions
            alarm, attack = event["is_anomaly"], labels[key]
            assert type(alarm) is type(attack) is bool
            outcome = ("T" if alarm == attack else "F") + ("P" if alarm else "N")
            confusion[outcome] += 1
            decisions[key] = alarm
            spec = case_specs.get((row["dataset"], event["window_start_utc"]))
            if spec and row["mode"] == "static":
                assert outcome == spec[1]
                cases.append([spec[0], *[event["counts"][k] for k in ["tcp", "udp", "ssdp", "arp"]],
                              f"{event['composition_score']:.4f}",
                              *[f"{event['feature_margins'][name]:.3f}" for name in
                                ["composition", "total", "arp"]], outcome])
        assert decisions.keys() == labels.keys()
        assert list(confusion.values()) == [row[k] for k in
               ["true_positive", "false_positive", "false_negative", "true_negative"]]
        if row["dataset"] in final_decisions:
            assert decisions == final_decisions[row["dataset"]]
        final_decisions[row["dataset"]] = decisions
        if row["mode"] == "static":
            final_rows.append([NAMES[row["dataset"]], *metrics(row)])
            for interval in row["interval_results"]:
                interval_rows.append([NAMES[row["dataset"]],
                                      r"\path{" + interval["attack_type"] + "}",
                                      "Yes" if interval["detected"] else "No",
                                      "--" if interval["delay_seconds"] is None else
                                      f"{interval['delay_seconds']:.0f}",
                                      "Yes" if interval["alert_before_attack_end"] else "No"])
    final_rows.append(["Pooled", *metrics(final["pooled"][0])])
    assert final["pooled"][0]["window_count"] == 1008
    assert len(interval_rows) == 9
    rows("final", final_rows)
    rows("final_intervals", interval_rows)
    assert len(cases) == 5
    rows("event_cases", sorted(cases))
    protocol = read("reports/final_evaluation/protocol.json")
    regression = read("reports/scoring_order_verification.json")
    frozen = protocol["input_and_code_sha256"]
    superseded = {}
    for path, expected in frozen.items():
        candidate = Path(path) if Path(path).is_absolute() else ROOT / path
        assert candidate.exists(), path
        actual = hashlib.sha256(candidate.read_bytes()).hexdigest()
        if actual != expected:
            assert path.startswith("src/"), path
            assert regression["source_sha256"].get(path) == actual, path
            superseded[path] = {"final_replay_sha256": expected, "current_sha256": actual,
                                "verification": "reports/scoring_order_verification.json"}
    for path, expected in {**regression["input_sha256"], **regression["source_sha256"]}.items():
        assert hashlib.sha256((ROOT / path).read_bytes()).hexdigest() == expected, path

    legacy, concentration, legacy_plot = [], [], []
    variants = [("adaptive_threshold", "Threshold 144"), ("periodic_refit", "Refit 144/144"),
                ("periodic_refit_288_240", "Refit 288/240")]
    for dataset in ["UNSW-Chromecast", "UNSW-Samsung-Camera"]:
        static = read(f"reports/{dataset}/evaluation_statistics.json")
        legacy.append([NAMES[dataset], "Static", *metrics(static)[:4], pct(static["f1_score"])])
        legacy_plot.append([dataset, 0, 100*static["f1_score"]])
        for i, (variant, title) in enumerate(variants, 1):
            base = f"reports/experiments/legacy/{dataset}/{variant}"
            result, update = read(base + "/evaluation_statistics.json"), read(base + "/adaptation.json")
            legacy.append([NAMES[dataset], title, *metrics(result)[:4], pct(result["f1_score"])])
            legacy_plot.append([dataset, i, 100*result["f1_score"]])
            if variant != "adaptive_threshold":
                before, after = sum(update["initial_alpha"]), sum(update["final_alpha"])
                concentration.append([NAMES[dataset], title, f"{before:.2f}",
                                      f"{after:.2f}", f"{after/before:.2f}"])
    rows("legacy", legacy)
    rows("concentration", concentration)
    for dataset in ["UNSW-Chromecast", "UNSW-Samsung-Camera"]:
        csv_rows("legacy_" + dataset, ["mode", "f1"],
                 [[i, f] for d, i, f in legacy_plot if d == dataset])

    decision = read("reports/detection_decision.json")
    pooled = {(r["mode"], r["policy"], r["variant"]): r for r in decision["aggregate_results"]}
    comparisons = []
    for mode, policy, name in [("static", "conservative", "Static"),
                                ("adaptive_threshold", "conservative", "Threshold, conservative"),
                                ("periodic_refit", "conservative", "Refit, conservative"),
                                ("adaptive_threshold", "legacy", "Threshold, legacy"),
                                ("periodic_refit", "legacy", "Refit, legacy")]:
        a, b = pooled[mode, policy, "baseline"], pooled[mode, policy, "hybrid"]
        for r in (a, b): metrics(r)
        comparisons.append([name, pct(a["f1_score"]), pct(b["f1_score"]),
                            b["true_positive"], b["false_positive"], b["false_negative"]])
    rows("scoring_comparison", comparisons)

    benchmark = read("reports/D-LinkDayCam5/lm_backend_benchmark.json")
    timing = []
    fields = [("model_fit_median_seconds", "Complete fit", 1e3, "ms"),
              ("likelihood_matrix_median_seconds", "Matrix kernel", 1e6, r"$\mu$s"),
              ("single_window_score_median_seconds", "Window score", 1e6, r"$\mu$s")]
    for field, title, scale, unit in fields:
        a, b = (benchmark["backends"][k][field] for k in ("lm", "scipy"))
        timing.append([title, f"{a*scale:.3f}", f"{b*scale:.3f}", f"{a/b:.3f}", unit])
    rows("backend_timing", timing)
    checks = read("reports/detection_backend_checks.json")
    rows("backend_agreement", [[NAMES[r["dataset"]],
         f"{r['comparisons']['alpha_maximum_relative_difference']:.3g}",
         f"{r['comparisons']['score_maximum_absolute_difference']:.3g}",
         r["comparisons"]["decision_mismatch_count"]] for r in checks])
    for r in checks:
        assert r["comparisons"]["decision_mismatch_count"] == 0
        csv_rows("backend_" + r["dataset"], ["operation", "ratio"],
                 [[i, r["comparisons"]["lm_over_scipy_runtime_ratio"][f]]
                  for i, (f, _, _, _) in enumerate(fields, 1)])

    aggregate = read("reports/D-LinkDayCam5/lm_professor_experiment.json")
    aggregate_rows = []
    for backend in ["lm", "scipy"]:
        records = [r for r in aggregate["records"] if r["backend"] == backend]
        assert len(records) == 84
        aggregate_rows.append([backend.upper() if backend == "lm" else "SciPy",
                               len(records), sum(r["fit"]["converged"] for r in records),
                               f"{sum(r['fit']['likelihood_seconds'] for r in records):.3f}",
                               f"{sum(r['fit']['wall_seconds'] for r in records):.3f}"])
    rows("aggregate", aggregate_rows)

    durations = read("reports/window_size/results.json")["results"]
    duration_rows, adaptation_rows, common_rows = [], [], []
    for dataset in ["UNSW-Chromecast", "UNSW-Samsung-Camera"]:
        plot = []
        for minutes in [10, 20, 30, 60]:
            matches = [r for r in durations if r["dataset"] == dataset and r["minutes"] == minutes
                       and r["partition"] == "development_test" and r["mode"] == "static"]
            assert len(matches) == 1
            row = matches[0]
            metrics(row)
            duration_rows.append([NAMES[dataset], minutes, pct(row["f1_score"]),
                                  f"{row['detected_attack_intervals']}/{row['attack_intervals']}",
                                  row["alerts_before_attack_end"],
                                  f"{row['false_alerts_per_24h']:.2f}",
                                  f"{row['median_delay_seconds']/60:.2f}"])
            plot.append([minutes, 100*row["f1_score"], row["median_delay_seconds"]/60,
                         100*row["common_10m_metrics"]["f1_score"]])
            common_rows.append([NAMES[dataset], minutes, pct(row["common_10m_metrics"]["f1_score"])])
        csv_rows("duration_" + dataset, ["minutes", "f1", "delay", "common_f1"], plot)
    for minutes in [30, 60]:
        for partition in ["development_test", "final_test"]:
            a, b = [next(r for r in durations if r["dataset"] == "UNSW-Samsung-Camera"
                         and r["minutes"] == minutes and r["partition"] == partition and r["mode"] == mode)
                    for mode in ["static", "adaptive_threshold"]]
            adaptation_rows.append([minutes, "Development" if partition == "development_test" else "Later audit",
                                    pct(a["f1_score"]), pct(b["f1_score"]),
                                    a["false_positive"], b["false_positive"]])
    rows("duration", duration_rows)
    rows("duration_adaptation", adaptation_rows)
    rows("duration_common_grid", common_rows)
    hourly = next(r for r in durations if r["dataset"] == "UNSW-Samsung-Camera"
                  and r["minutes"] == 60 and r["mode"] == "static"
                  and r["partition"] == "development_test")
    n = hourly["calibration_windows"]
    quantile_ranks.extend([["Samsung camera, hourly study", n, f"{1 + (n - 1)*.01:.2f}"],
                           ["Minimum permitted support", 30, f"{1 + 29*.01:.2f}"]])
    rows("quantile_ranks", quantile_ranks)

    short, long = [read(f"reports/edge/simulation-{n}.json") for n in [2000, 20000]]
    edge = []
    for label, a, b in [
        ("Input windows", short["input_windows"], long["input_windows"]),
        ("Scored windows", short["measurements"]["scored_windows"], long["measurements"]["scored_windows"]),
        ("Elapsed replay (s)", short["elapsed_seconds"], long["elapsed_seconds"]),
        ("Mean processing (ms)", short["mean_processing_seconds"]*1000, long["mean_processing_seconds"]*1000),
        ("Worst window (s)", short["measurements"]["latency_max_seconds"], long["measurements"]["latency_max_seconds"]),
        ("Estimator calls", short["measurements"]["estimator_calls"], long["measurements"]["estimator_calls"]),
        ("Worst estimator call (s)", short["measurements"]["fit_max_seconds"], long["measurements"]["fit_max_seconds"]),
        ("Peak process RSS (MiB)", short["peak_process_rss_bytes"]/2**20, long["peak_process_rss_bytes"]/2**20),
        ("Peak sampled RSS (MiB)", max(s["rss_bytes"] for s in short["samples"])/2**20,
         max(s["rss_bytes"] for s in long["samples"])/2**20),
        ("Retained state (KiB)", sum(short["state_files_bytes"].values())/1024,
         sum(long["state_files_bytes"].values())/1024),
        ("Application logs (KiB)", sum(short["log_files_bytes"].values())/1024,
         sum(long["log_files_bytes"].values())/1024),
        ("Promoted updates", short["measurements"]["promoted_updates"], long["measurements"]["promoted_updates"]),
    ]:
        edge.append([label, str(a) if isinstance(a, int) else f"{a:.3f}",
                     str(b) if isinstance(b, int) else f"{b:.3f}"])
    rows("edge", edge)
    csv_rows("edge_memory", ["windows", "rss", "state"],
             [[s["after_input_windows"], s["rss_bytes"]/2**20, s["state_bytes"]/1024]
              for s in long["samples"]])
    read("reports/edge/simulation-environment.json")
    read("reports/final_evaluation/verification.json")
    record_path = "docs/lm_backend_change_record.tex"
    SOURCES[record_path] = hashlib.sha256((ROOT / record_path).read_bytes()).hexdigest()
    manifest = {"generator": "thesis/generate_evidence.py", "source_sha256": SOURCES,
                "frozen_final_inputs_checked": len(frozen),
                "chronology_checks": chronology,
                "final_events_checked": sum(len(d) for d in final_decisions.values()) * 3,
                "superseded_source_records": superseded,
                "boundary": "Derived presentation of retained experiments; no detector run was repeated."}
    (OUT / "evidence_manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(f"Generated thesis tables/plot data from {len(SOURCES)} records; verified {len(frozen)} frozen inputs.")


if __name__ == "__main__":
    main()
